    runtime = {q["Id"]: q for q in quests["Quests"]}
    lookup = {t["id"]: t for t in catalog["tasks"]}
    def runtime_prerequisites(task_id):
        result = []
        for dep in lookup[task_id]["prerequisites"]:
            result.extend([dep] if dep in runtime else runtime_prerequisites(dep))
        return list(dict.fromkeys(result))
    english = ["Settle in", "Stable survival", "Infrastructure", "Exploration and temperature", "Sustainable development", "Space"]
    quests["Phases"] = [dict(Id=c["id"], Title=f'第{c["order"]}章 · {c["title"]}', Desc=c["outcome"], TitleEn=f'Chapter {c["order"]} - {english[i]}', DescEn=c["outcome"]) for i, c in enumerate(catalog["chapters"])]
    for i, t in enumerate(catalog["tasks"]):
        chapter = next(c for c in catalog["chapters"] if c["id"] == t["chapterId"])
        main = chapter["mainTaskIds"]
        if t["track"] == "main":
            at = main.index(t["id"])
            next_id = main[at+1] if at+1 < len(main) else None
            t["successNext"] = "下一项主线：" + lookup[next_id]["title"] if next_id else "核对本章能力后进入下一章；选做路线按需查阅。"
        else:
            t["successNext"] = "回到本章主线；此路线按资源和当前存档内容选择，不作为毕业必做条件。"
        if t["id"] in runtime:
            q = runtime[t["id"]]
            q.update(Phase=t["chapterId"], Order=i+1, Requires=runtime_prerequisites(t["id"]))
    for t in catalog["tasks"]:
        purpose, prep, steps, running, failure = DETAILS[t["id"]]
        q = runtime.get(t["id"])
        if q and q["Objectives"]:
            automatic = "自动检查：" + "；".join(dict.fromkeys(o["Label"] for o in q["Objectives"])) + "。"
            if any(o["Type"] == "buildingBuilt" for o in q["Objectives"]):
                automatic += "当前自动判定只统计建成数量；运行效果需按下列步骤自行核对。"
        elif q:
            automatic = "知识任务：接取后由玩家确认；阅读页面不自动证明设备运行成功。"
        else:
            automatic = "教学目录项：当前未接入独立自动任务判定，可按步骤自查；不自动发奖。"
        teaching = {
            "purpose": purpose, "preparation": prep, "steps": steps.split("→"),
            "runningChecks": running, "commonFailures": failure, "completion": automatic,
            "requiredOrOptional": "本章主线" if t["track"] == "main" else "按资源与存档路线选做",
            "next": t["successNext"],
        }
        t["teaching"] = teaching
        if q:
            q["Teaching"] = teaching
    for c in catalog["chapters"]:
        brief, color, icons = CHAPTERS[c["id"]]
        c.update(backgroundBrief=brief, backgroundStatus="implementedNativeScene", backgroundColor=color, backgroundIcons=icons)
    quests["Version"] = 8
    catalog["catalogVersion"] = 2
    for p, data in ((qp, quests), (cp, catalog)):
        p.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    report = ["# 六章教学细化与背景设计", "", "36 个原有任务保留 ID、完成条件与奖励，按六章学习框架调整顺序和前置；选做路线不阻挡主线。45 个目录项均有教学步骤。9 个未接入自动任务的目录项标为教学自查，其准备步骤显示在后续教学中，但不伪造自动完成记录。", ""]
    for c in catalog["chapters"]:
        report.extend(["## " + c["title"], "", c["backgroundBrief"] + "。背景使用原版图标、主题色与网格，文字置于独立清晰区域。", ""])
        for t in (x for x in catalog["tasks"] if x["chapterId"] == c["id"]):
            v = t["teaching"]
            report.extend(["### " + t["title"] + "（" + t["id"] + "）", "", "- 路线：" + v["requiredOrOptional"], "- 用途：" + v["purpose"], "- 准备：" + v["preparation"], "- 步骤：" + " → ".join(v["steps"]), "- 运行核对：" + v["runningChecks"], "- 常见问题：" + v["commonFailures"], "- 完成判定：" + v["completion"], "- 下一步：" + v["next"], ""])
    (ROOT / "Curriculum/全任务细化与背景设计.md").write_text("\n".join(report), encoding="utf-8")

